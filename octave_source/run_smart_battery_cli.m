function run_smart_battery_cli(pv_file, load_file, cap_pv, Ab, rp, fit, max_battery_kwh, profile_is_base_pv, installed_cost_per_kwh)
%RUN_SMART_BATTERY_CLI File-based CLI bridge used by Django + GNU Octave.
%
% The Python web process writes PV/load arrays to temporary CSV files, then
% invokes this function with octave-cli. Keeping the large arrays out of the
% command line avoids shell/argument-size problems for full-year profiles.

pv_input = dlmread(pv_file, ',');
ld_input = dlmread(load_file, ',');

out = smart_battery_optimize( ...
    pv_input, ...
    ld_input, ...
    cap_pv, ...
    Ab, ...
    rp, ...
    fit, ...
    max_battery_kwh, ...
    profile_is_base_pv, ...
    installed_cost_per_kwh ...
);

% Emit one machine-readable line. Other Octave warnings/output can safely exist;
% Python searches specifically for this marker.
fprintf('__SMART_BATTERY_RESULT__');
for i = 1:numel(out)
    if i > 1
        fprintf(',');
    end
    fprintf('%.17g', out(i));
end
fprintf('\n');
end
